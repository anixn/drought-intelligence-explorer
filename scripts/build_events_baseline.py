#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""build_events_baseline.py — observed 1981-2020 drought-event baseline (M5.8 / E14).

Computes, per district and per standardised variable, the frozen v1.0 event
machinery (runs analysis, Yevjevich 1967) over the OBSERVED era-B record
(data/parquet/observed, committed) for the 1981-2020 baseline window. The
output (`data/events/baseline_1981_2020.json`) is the comparison baseline the
#projections events panel evaluates era-C ensemble-median events against.

Frozen methodology (identical to the v1.0 events engine / analytics.js
`findEvents`):
  - runs of consecutive months with value <= threshold
  - threshold = upper bound of the moderate class (SPI/SPEI: -1.0)
  - minimum duration 3 months; missing months break runs (no interpolation)
  - severity = sum(threshold - x) over the run
  - events touching the window edge are censored (flagged, not dropped)

Only the era-B store is read — the era-C comparison side is computed live in
the browser from the published era-C partitions, so the two sides of the
comparison come from the same frozen machinery. Deterministic output; the
file is re-generated byte-identical for the same inputs.

Usage:
    python scripts/build_events_baseline.py
    python scripts/build_events_baseline.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import pathlib
import sys

import pyarrow.parquet as pq

REPO = pathlib.Path(__file__).resolve().parents[1]
OBSERVED_DIR = REPO / "data" / "parquet" / "observed"
OUT_JSON = REPO / "data" / "events" / "baseline_1981_2020.json"

VARIABLES = ["spi_01", "spi_03", "spi_06", "spi_12",
             "spei_01", "spei_03", "spei_06", "spei_12"]
WINDOW = (1981, 2020)
THRESHOLD = -1.0
MIN_DURATION = 3

SPI_SPEI = {"spi", "spei"}


def find_runs(values):
    """Maximal runs of value <= THRESHOLD with duration >= MIN_DURATION.
    Non-finite months break runs. Mirrors analytics.js findEvents exactly."""
    events = []
    start = -1
    n = len(values)
    for j in range(n + 1):
        v = values[j] if j < n else float("nan")
        in_run = math.isfinite(v) and v <= THRESHOLD
        if in_run and start < 0:
            start = j
        if not in_run and start >= 0:
            dur = j - start
            if dur >= MIN_DURATION:
                seg = values[start:j]
                severity = sum(THRESHOLD - x for x in seg)
                events.append({
                    "start": start, "end": j - 1, "duration": dur,
                    "severity": round(severity, 6),
                })
            start = -1
    return events


def district_metrics(values):
    """Event metrics for one continuous monthly series (NaN breaks runs)."""
    events = find_runs(values)
    drought_months = sum(1 for v in values if math.isfinite(v) and v <= THRESHOLD)
    valid_months = sum(1 for v in values if math.isfinite(v))
    durations = [e["duration"] for e in events]
    n = len(events)
    censored = sum(
        1 for e in events if e["start"] == 0 or e["end"] == len(values) - 1)
    mean_dur = (sum(durations) / n) if n else None
    med_dur = (sorted(durations)[n // 2]
               if n else None) if n % 2 else (
        (sorted(durations)[n // 2 - 1] + sorted(durations)[n // 2]) / 2
        if n else None)
    return {
        "n_events": n,
        "events_per_year": round(n / (WINDOW[1] - WINDOW[0] + 1), 6)
        if n else 0.0,
        "mean_duration": round(mean_dur, 4) if mean_dur is not None else None,
        "median_duration": round(med_dur, 4) if med_dur is not None else None,
        "max_duration": max(durations) if durations else 0,
        "total_severity": round(sum(e["severity"] for e in events), 4),
        "drought_months": drought_months,
        "valid_months": valid_months,
        "n_events_censored": censored,
    }


def build() -> dict:
    variables = {}
    for var in VARIABLES:
        fam = var.split("_")[0]
        if fam not in SPI_SPEI:
            continue  # era C publishes SPI/SPEI only; baseline matches it
        table = pq.read_table(
            OBSERVED_DIR / f"variable={var}" / "part-0.parquet")
        ids = table.column("district_id").to_pylist()
        years = table.column("year").to_pylist()
        months = table.column("month").to_pylist()
        vals = table.column("value").to_pylist()
        series = {}
        for d, y, m, v in zip(ids, years, months, vals):
            if not (WINDOW[0] <= y <= WINDOW[1]):
                continue
            series.setdefault(d, {})[(y, m)] = v
        districts = {}
        for d, cellmap in series.items():
            keys = sorted(cellmap)
            values = [cellmap[k] if cellmap[k] is not None else float("nan")
                      for k in keys]
            districts[d] = district_metrics(values)
        variables[var] = {
            "threshold": THRESHOLD,
            "min_duration": MIN_DURATION,
            "n_districts": len(districts),
            "districts": districts,
        }
    doc = {
        "schema": "die-events-baseline/1.0",
        "source": "data/parquet/observed (era B, committed store)",
        "window": list(WINDOW),
        "method": "frozen v1.0 runs analysis (Yevjevich 1967): consecutive "
                  "months <= -1.0, min duration 3, missing months break runs, "
                  "severity = sum(-1.0 - x); edge events flagged censored, "
                  "never dropped; identical to the browser-side machinery "
                  "(analytics.js findEvents) used on the era-C side",
        "variables": variables,
    }
    return doc


def verify(doc: dict) -> list[str]:
    fails = []
    for var, blk in doc["variables"].items():
        if blk["n_districts"] != len(blk["districts"]):
            fails.append(f"{var}: n_districts mismatch")
        for d, met in blk["districts"].items():
            if met["valid_months"] == 0:
                fails.append(f"{var}/{d}: zero valid months")
                continue
            if met["n_events_censored"] > met["n_events"]:
                fails.append(f"{var}/{d}: censored > n_events")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if args.check:
        doc = json.loads(OUT_JSON.read_text(encoding="utf-8"))
    else:
        doc = build()
    fails = verify(doc)
    if fails:
        for f in fails:
            print("FAIL:", f)
        return 1
    total = sum(b["n_districts"] for b in doc["variables"].values())
    print(f"round-trip verified: {len(doc['variables'])} variables, "
          f"{total} district records")
    if args.check:
        print("CHECK PASS (existing file untouched)")
        return 0
    payload = json.dumps(doc, sort_keys=True, separators=(",", ":"),
                         ensure_ascii=False) + "\n"
    data = payload.encode("utf-8")
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_bytes(data)
    print(f"wrote {OUT_JSON.relative_to(REPO)} ({len(data)} bytes, "
          f"sha256 {hashlib.sha256(data).hexdigest()[:16]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
