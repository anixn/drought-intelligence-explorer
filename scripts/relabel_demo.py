def main() -> int:
    with open(META, encoding="utf-8") as fh:
        meta = json.load(fh)

    if meta.get("data_mode") == "static-demonstration":
        print("already relabelled — nothing to do")
        return 0

    before = {
        k: meta.get(k)
        for k in ("data_mode", "data_provenance", "disclaimer", "random_seed")
    }

    meta["data_mode"] = "static-demonstration"
    meta["data_provenance"] = PROVENANCE
    meta["disclaimer"] = DISCLAIMER
    meta["random_seed"] = 42
    meta["sources"] = SOURCES

    with open(META, "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")

    print("relabelled", os.path.relpath(META, ROOT))
    print("  data_mode:      ", before["data_mode"], "->", meta["data_mode"])
    print("  random_seed:    ", before["random_seed"], "->", meta["random_seed"])
    print("  sources:        ", len(SOURCES), "entries (1 synthetic current + boundaries + recommended)")
    print("  untouched:      indicators, classes/thresholds, seasons, period, citation,")
    print("                   reference_period, methodology_version, aggregation, events")
    return 0


if __name__ == "__main__":
    sys.exit(main())
